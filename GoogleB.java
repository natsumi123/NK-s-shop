package first;

public class GoogleB {
	
	
	private int id;
	
	private String name;
	
	
	private int zaikosu;
	
	
	private int tanka;
	
	private String url;
	
	private int hanbaiFlag;
	

	public String getUrl() {
		return url;
	}


	public void setUrl(String url) {
		this.url = url;
	}



	public int getId() {
		return id;
	}


	public void setId(int id) {
		this.id = id;
	}


	public String getName() {
		return name;
	}


	public void setName(String name) {
		this.name = name;
	}


	public int getZaikosu() {
		return zaikosu;
	}


	public void setZaikosu(int zaikosu) {
		this.zaikosu = zaikosu;
	}


	public int getTanka() {
		return tanka;
	}


	public void setTanka(int tanka) {
		this.tanka = tanka;
	}


	public int getHanbaiFlag() {
		return hanbaiFlag;
	}


	public void setHanbaiFlag(int hanbaiFlag) {
		this.hanbaiFlag = hanbaiFlag;
	}
	

	
	
	

}
